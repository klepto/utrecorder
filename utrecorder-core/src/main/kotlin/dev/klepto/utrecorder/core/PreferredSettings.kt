package dev.klepto.utrecorder.core

import dev.klepto.utrecorder.ut99.UtIni

/**
 * The preferred settings of a recording pass, layered over the run's own copies of the installation's game and user
 * configurations: they are written over the keys they name on top of whatever a fresh or updated installation
 * materializes with, so an installation that carries more, or newer, settings keeps every key the preferred settings
 * leave unnamed.
 *
 * The values are those of the converter's `settings/converter.UnrealTournament.ini` and
 * `settings/converter.User.ini`, held as data rather than flat files so they travel through the instance builder's
 * `gameIni {}` / `userIni {}` edits instead of replacing a configuration file outright. Every named key is written
 * into the ini at the full list of values the converter held there: the preferred values take the copy's own entry
 * positions, entries the copy held beyond them are removed, and the ones left over are appended to the section.
 *
 * The two keys the pass itself owns are not in the data: `[Engine.Engine] ViewportManager` is written from the
 * client the run runs its platform's build through, and `Console` from the recorder console the run plays its demo
 * through.
 */
object PreferredSettings {
    /**
     * Writes the preferred game settings into [ini], naming [client] the engine's viewport manager, the client class
     * the run draws into, and [console] the engine's console, the recorder console class the run plays its demo
     * through, in place of the installation's own; the `[FirstRun]` patch number the preferred settings carry keeps
     * the safe-mode selection screen from showing up on launch.
     */
    fun applyGameIni(
        ini: UtIni,
        client: String,
        console: String,
    ) {
        apply(ini, gameIni)
        ini["Engine.Engine", "ViewportManager"] = client
        ini["Engine.Engine", "Console"] = console
    }

    /**
     * Writes the preferred user settings into [ini].
     */
    fun applyUserIni(ini: UtIni) = apply(ini, userIni)

    /**
     * Writes every key the given [settings] name into [ini], replacing the entries the ini already holds for it:
     * the preferred values take the ini's own positions in order, and the ones left over are appended at the end of
     * the section. The section appears in the file when the ini holds none of it, and every entry of the key the
     * preferred settings do not refill is gone.
     */
    private fun apply(
        ini: UtIni,
        settings: List<Triple<String, String, String>>,
    ) {
        settings
            .groupBy({ it.first to it.second }) { it.third }
            .forEach { (target, values) ->
                val (section, key) = target
                val existing = ini[section, key]
                if (existing.isEmpty()) {
                    values.forEach { ini.add(section, key, it) }
                    return@forEach
                }

                values.forEachIndexed { index, value ->
                    when {
                        index < existing.size -> ini.replace(section, key, existing[index], value)
                        else -> ini.add(section, key, value)
                    }
                }
                existing.drop(values.size).forEach { ini.remove(section, key, it) }
            }
    }

